-- Current single-exchange app. Independent of the historical santa_private schema.
begin;
create schema if not exists santa_app;
revoke all on schema santa_app from public, anon, authenticated;
set local search_path to santa_app, pg_catalog;
create table approved_people (
  id integer generated by default as identity primary key,
  name text not null
);
create unique index approved_name_unique on approved_people(lower(name));
create table users (
  id text primary key, name_key text not null unique, name text not null,
  password_hash text not null, admin integer not null default 0 check(admin in (0,1)),
  wishlist text not null default '',
  approved_person_id integer unique references approved_people(id),
  recovery_question text, recovery_answer_hash text
);
create unique index one_admin on users(admin) where admin = 1;
create table exchange (id integer primary key check(id=1), enabled integer not null default 0 check(enabled in (0,1)), revision integer not null default 0);
insert into exchange(id) values(1);
create table assignments (
  giver text primary key references users(id), recipient text not null unique references users(id), check(giver<>recipient)
);
create table sessions (token_hash text primary key, user_id text not null references users(id), expires bigint not null);
create table password_resets (token_hash text primary key, user_id text not null unique references users(id), expires bigint not null);
create table attempts (key text primary key, count integer not null, reset bigint not null);
create table draw_reset_requests (
  token_hash text primary key, admin_id text not null references users(id), session_hash text not null,
  revision integer not null, credential_hash text not null, reason text not null, expires bigint not null
);
create table draw_reset_history (
  id text primary key, admin_id text not null, admin_name text not null, reason text not null,
  revision integer not null, participant_count integer not null, created bigint not null, backup_path text not null
);
-- Private, durable snapshots are committed atomically with each draw reset.
-- These are an application recovery archive, not a replacement for DB backups.
create table draw_backups (id text primary key, created bigint not null, snapshot jsonb not null);
create function validate_participant() returns trigger language plpgsql set search_path = pg_catalog, santa_app as $$
begin
  if new.admin = 0 and (new.approved_person_id is null or not exists (
    select 1 from approved_people where id = new.approved_person_id and lower(name) = lower(new.name)
  )) then raise exception 'An approved participant name is required'; end if;
  return new;
end $$;
create trigger approved_participant before insert or update of name,approved_person_id,admin on users for each row execute function validate_participant();
create function validate_assignment() returns trigger language plpgsql set search_path = pg_catalog, santa_app as $$
begin
  if exists(select 1 from users where id in (new.giver,new.recipient) and admin=1) then
    raise exception 'Admin cannot participate';
  end if;
  return new;
end $$;
create trigger participant_assignment before insert or update on assignments for each row execute function validate_assignment();
-- No browser/Data API role may read credentials, sessions or assignments.
do $$ declare t record; begin
  for t in select tablename from pg_tables where schemaname='santa_app' loop
    execute format('alter table santa_app.%I enable row level security', t.tablename);
  end loop;
end $$;
revoke all on all tables in schema santa_app from public, anon, authenticated;
revoke all on all sequences in schema santa_app from public, anon, authenticated;
revoke all on all functions in schema santa_app from public, anon, authenticated;
commit;
